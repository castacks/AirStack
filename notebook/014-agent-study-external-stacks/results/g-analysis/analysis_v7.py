#!/usr/bin/env python3
"""analysis_v7.py — campaign v7-external (E1 Unified Autonomy Stack, E2
Aerostack2) beside campaign v6 (AirStack arms A1–A4, post-relabel labels).

Reuses notebook 011's analysis.py loader/figure helpers for the v6 arms
(so the v6 numbers are the recomputed ones of record) and loads v7 trials
from agent_study/runs/E*_*. The two campaigns have different config hashes
by construction and are NEVER pooled; every table/figure keeps them side by
side.

Outputs (this directory): analysis_v7_output.md, rung_survival_ext.{pdf,png},
tab_agents_external.tex.
"""
import hashlib
import json
import re
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
RUNS = REPO / "agent_study" / "runs"
V6_DIR = REPO / "notebook" / "011-agent-study-v6-trials" / "results" / "d-analysis"
sys.path.insert(0, str(V6_DIR))
import analysis as v6  # noqa: E402

V7_CONFIG = REPO / "agent_study" / "config" / "study_config_v7_external.yaml"
V7_SHA = hashlib.sha256(V7_CONFIG.read_bytes()).hexdigest()
V7_RE = re.compile(r"^(E[12])_(claude-(?:sonnet|opus)-5)_ladder_claude_(\d{3})$")
E_ARMS = ["E1", "E2"]
E_LABEL = {"E1": "E1, Unified Autonomy Stack", "E2": "E2, Aerostack2"}
E_COLOR = {"E1": "#7a3e9d", "E2": "#0d8a6a"}
E_MARKER = {"E1": "P", "E2": "X"}
MODELS = v6.MODELS
RUNG_NUM = v6.RUNG_NUM
flags = []


def flag(msg):
    flags.append(msg)
    print(f"  !! {msg}")


def load_v7():
    trials = []
    if not RUNS.exists():
        return trials
    for d in sorted(RUNS.iterdir()):
        m = V7_RE.match(d.name)
        if not m or not (d / "results.json").exists():
            continue
        r = json.loads((d / "results.json").read_text())
        if r.get("smoke"):
            continue
        if r["config_sha256"] != V7_SHA:
            flag(f"{d.name}: config_sha256 {r['config_sha256'][:8]} != v7 {V7_SHA[:8]} — excluded")
            continue
        if r["prompt_sha256"][:8] != "afad954d":
            flag(f"{d.name}: composed prompt sha {r['prompt_sha256'][:8]} != frozen v4 afad954d")
        r["_dir"] = d
        pod = d / "pod_env.json"
        r["_pod"] = json.loads(pod.read_text()) if pod.exists() else {}
        trials.append(r)
    return trials


def survival_of(ts):
    if not ts:
        return [float("nan")] * 8
    return [sum(RUNG_NUM[t["highest_rung_passed"]] >= r for t in ts) / len(ts) for r in range(1, 9)]


def stats_for(ts):
    if not ts:
        return None
    rungs = [RUNG_NUM[t["highest_rung_passed"]] for t in ts]
    hours = [t["agent"]["agent_wallclock_s"] / 3600 for t in ts]
    calls = [t["judge_invocations"] for t in ts]
    costs = [t["agent"]["cost_usd"] for t in ts if t["agent"]["cost_usd"] is not None]
    return {"n": len(ts), "r8": sum(x == 8 for x in rungs), "mean_rung": statistics.mean(rungs),
            "hours": v6.mean_sd(hours), "calls": v6.mean_sd(calls),
            "cost": v6.mean_sd(costs), "cost_n": len(costs)}


def main():
    out = []

    def emit(s=""):
        print(s)
        out.append(s)

    v6_trials = v6.load_trials()          # 40 trials, post-relabel arm labels
    v7_trials = load_v7()
    emit("# Campaign v7-external beside campaign v6 (generated by analysis_v7.py)")
    emit()
    emit(f"v6 trials: {len(v6_trials)} (config {v6.CONFIG_SHA[:8]}); "
         f"v7 trials: {len(v7_trials)} (config {V7_SHA[:8]}) from {RUNS}")
    by_cell = {}
    for t in v6_trials:
        by_cell.setdefault((t["arm"], t["model"]), []).append(t)
    for t in v7_trials:
        by_cell.setdefault((t["arm"], t["model"]), []).append(t)
    for ts in by_cell.values():
        ts.sort(key=lambda t: t["trial_index"])

    # ------------------------------------------------------------ v7 matrix
    emit()
    emit("## v7 score matrix (highest_rung_passed)")
    emit()
    emit("| Cell | trials (index: rung, judge calls, agent h, USD) |")
    emit("|---|---|")
    for arm in E_ARMS:
        for model in MODELS:
            ts = by_cell.get((arm, model), [])
            cells = [f"#{t['trial_index']}: {t['highest_rung_passed'] or 'NULL'}, "
                     f"{t['judge_invocations']}, {t['agent']['agent_wallclock_s'] / 3600:.1f}h, "
                     f"{(t['agent']['cost_usd'] or float('nan')):.2f}" for t in ts]
            emit(f"| {arm} {model.split('-')[1]} (n={len(ts)}) | " + ("; ".join(cells) or "—") + " |")

    # ------------------------------------------------------------ survival
    emit()
    emit("## Rung survival (fraction of trials with score >= rung), v6 arms then v7 arms")
    emit()
    emit("| Arm | n | " + " | ".join(f">=R{r}" for r in range(1, 9)) + " |")
    emit("|---|---|" + "---|" * 8)
    survival = {}
    for arm in v6.ARMS:
        pooled = [t for m in MODELS for t in by_cell.get((arm, m), [])]
        survival[arm] = survival_of(pooled)
        emit(f"| {arm} (v6) | {len(pooled)} | " + " | ".join(f"{v:.2f}" for v in survival[arm]) + " |")
    for arm in E_ARMS:
        pooled = [t for m in MODELS for t in by_cell.get((arm, m), [])]
        survival[arm] = survival_of(pooled)
        emit(f"| {arm} (v7) | {len(pooled)} | "
             + " | ".join("—" if v != v else f"{v:.2f}" for v in survival[arm]) + " |")
    survival_pm = {}
    emit()
    emit("Per model:")
    emit()
    emit("| Cell | n | " + " | ".join(f">=R{r}" for r in range(1, 9)) + " |")
    emit("|---|---|" + "---|" * 8)
    for arm in v6.ARMS + E_ARMS:
        for model in MODELS:
            ts = by_cell.get((arm, model), [])
            survival_pm[(arm, model)] = survival_of(ts)
            emit(f"| {arm} {model.split('-')[1]} | {len(ts)} | "
                 + " | ".join("—" if v != v else f"{v:.2f}" for v in survival_pm[(arm, model)]) + " |")

    # ------------------------------------------------------------ table rows
    emit()
    emit("## tab:agents rows (mean ± sd)")
    emit()
    emit("| Arm | n | R8 | mean rung | agent hours | judge calls | USD (n) |")
    emit("|---|---|---|---|---|---|---|")
    rows = []
    for arm in v6.ARMS + E_ARMS:
        pooled = [t for m in MODELS for t in by_cell.get((arm, m), [])]
        s = stats_for(pooled)
        if s is None:
            emit(f"| {arm} | 0 | — | — | — | — | — |")
            continue
        rows.append((arm, s))
        emit(f"| {arm} | {s['n']} | {s['r8']}/{s['n']} | {s['mean_rung']:.1f} | "
             f"{s['hours'][0]:.1f} ± {s['hours'][1]:.1f} | {s['calls'][0]:.1f} ± {s['calls'][1]:.1f} | "
             f"{s['cost'][0]:.2f} ± {s['cost'][1]:.2f} ({s['cost_n']}) |")
        if arm in E_ARMS:
            for model in MODELS:
                sm = stats_for(by_cell.get((arm, model), []))
                if sm:
                    emit(f"| — {arm} {model.split('-')[1]} | {sm['n']} | {sm['r8']}/{sm['n']} | "
                         f"{sm['mean_rung']:.1f} | {sm['hours'][0]:.1f} ± {sm['hours'][1]:.1f} | "
                         f"{sm['calls'][0]:.1f} ± {sm['calls'][1]:.1f} | "
                         f"{sm['cost'][0]:.2f} ± {sm['cost'][1]:.2f} ({sm['cost_n']}) |")

    # ------------------------------------------------------------ v7 environment record
    emit()
    emit("## v7 pod environment")
    emit()
    gpus = sorted({t["_pod"].get("gpu", "?") for t in v7_trials})
    drivers = sorted({t["_pod"].get("driver", "?") for t in v7_trials})
    commits = sorted({t["runner_commit"][:8] for t in v7_trials})
    emit(f"GPUs: {gpus}; drivers: {drivers}; runner commits: {commits}")

    if flags:
        emit()
        emit("## Flags")
        for f in flags:
            emit(f"- {f}")

    make_figure(survival, survival_pm, {a: len([t for m in MODELS for t in by_cell.get((a, m), [])])
                                        for a in v6.ARMS + E_ARMS})
    write_tab(rows)
    (HERE / "analysis_v7_output.md").write_text("\n".join(out) + "\n")
    return 0


def make_figure(survival, survival_pm, n_by_arm):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.family": "serif", "font.size": 8, "axes.labelsize": 8,
                         "legend.fontsize": 6.4, "pdf.fonttype": 42})
    x = list(range(1, 9))
    fig, ax = plt.subplots(figsize=(3.45, 2.4), dpi=300)
    for arm in v6.ARMS:  # v6 arms muted, for context
        y = survival[arm]
        ax.plot(x, y, color=v6.ARM_COLOR[arm], lw=1.0, ls=v6.ARM_LS[arm], alpha=0.55,
                marker=v6.ARM_MARKER[arm], ms=2.6, mfc="white", mew=0.8,
                label=v6.ARM_LABEL[arm] + " (v6)", clip_on=False, zorder=2)
    for arm in E_ARMS:
        y = survival[arm]
        if any(v != v for v in y) or n_by_arm[arm] == 0:
            continue
        lo, hi = zip(*[v6.wilson(p, n_by_arm[arm]) for p in y])
        ax.fill_between(x, lo, hi, color=E_COLOR[arm], alpha=0.10, lw=0)
        ax.plot(x, y, color=E_COLOR[arm], lw=1.8, marker=E_MARKER[arm], ms=4.0,
                mfc="white", mew=1.2, label=f"{E_LABEL[arm]} (v7, n={n_by_arm[arm]})",
                clip_on=False, zorder=4)
    v6.style_ax(ax)
    ax.set_xlabel("Ladder rung", color="#0b0b0b")
    ax.set_ylabel("Fraction of trials scoring $\\geq$ rung", color="#0b0b0b")
    ax.legend(loc="lower left", frameon=False, handlelength=2.0, borderaxespad=0.1, labelspacing=0.3)
    fig.tight_layout(pad=0.3)
    fig.savefig(HERE / "rung_survival_ext.pdf")
    fig.savefig(HERE / "rung_survival_ext.png")
    plt.close(fig)


def write_tab(rows):
    lines = [
        r"% Generated by notebook/014-agent-study-external-stacks/results/g-analysis/analysis_v7.py",
        r"% v6 rows recomputed from campaign 2026-08-icra27-vic-v6; E rows from 2026-09-icra27-vic-v7-external.",
        r"% Campaigns are reported side by side and never pooled (different config hashes; identical judge block).",
        r"\begin{tabular}{lcccc}",
        r"\toprule",
        r"Arm & R8 success & Hours & Judge calls & Cost (USD) \\",
        r"\midrule",
    ]
    for label, s in rows:
        if label == "E1":
            lines.append(r"\midrule")
        calls = "0 (by design)" if label == "A3" else f"${s['calls'][0]:.1f} \\pm {s['calls'][1]:.1f}$"
        lines.append(f"{label} & {s['r8']}/{s['n']} & ${s['hours'][0]:.1f} \\pm {s['hours'][1]:.1f}$ "
                     f"& {calls} & ${s['cost'][0]:.2f} \\pm {s['cost'][1]:.2f}$ ({s['cost_n']}) \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    (HERE / "tab_agents_external.tex").write_text("\n".join(lines))


if __name__ == "__main__":
    sys.exit(main())
